"""Review log — run by the Review log workflow on every push and every submitted review.

Every review the repository owner submits on a pull request, and every review
comment they leave, must have an entry in reviews/pr-<NNN>.md that links to it
(reviews/AGENTS.md). A missing entry fails the check; an entry whose outcome is
still open passes with a warning, since an open entry waits on the owner.
Pending reviews are invisible to the API until submitted, so they never count.
Neither do an agent session's own replies: they post under the owner's account
but end with the Claude Code footer, and the log holds the owner's comments only.

Standard library only, so the workflow runs it without installing anything.

Locally: GITHUB_REPOSITORY=owner/repo PR_NUMBER=7 python3 scripts/check_review_log.py
"""

import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import TypedDict, cast

API_URL = "https://api.github.com"
PAGE_SIZE = 100
LOG_PATH_TEMPLATE = "reviews/pr-{number:03d}.md"
# An agent session's reply, posted under the owner's account.
SESSION_FOOTER = "Generated by [Claude Code]"
PENDING_STATE = "PENDING"
ENTRY_BOUNDARY = re.compile(r"\n(?=#{2,3} )")
OPEN_OUTCOME = re.compile(r"\*\*Outcome:\*\* open\b")
HEADING_MARKS = re.compile(r"^#+ ")


class GitHubUser(TypedDict):
    login: str


class Review(TypedDict):
    id: int
    user: GitHubUser | None
    body: str | None
    state: str
    html_url: str


class ReviewComment(TypedDict):
    id: int
    user: GitHubUser | None
    body: str | None
    path: str
    line: int | None
    original_line: int | None
    html_url: str


class PullRequest(TypedDict):
    number: int


class PullRequestEvent(TypedDict, total=False):
    pull_request: PullRequest


@dataclass(frozen=True)
class ExpectedEntry:
    """One of the owner's review items, and the anchor its log entry must link to."""

    anchor: str
    label: str
    url: str


def fetch_json(path: str) -> object:
    """One GitHub REST response. CI passes the workflow token; a public repository answers without one."""
    headers = {"Accept": "application/vnd.github+json"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(f"{API_URL}{path}", headers=headers)
    try:
        with urllib.request.urlopen(request) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        raise RuntimeError(f"GitHub API {path}: {error.code}") from error


def fetch_all(path: str) -> list[object]:
    """Every page of a list endpoint."""
    items: list[object] = []
    separator = "&" if "?" in path else "?"
    page = 1
    while True:
        batch = cast(list[object], fetch_json(f"{path}{separator}per_page={PAGE_SIZE}&page={page}"))
        items.extend(batch)
        if len(batch) < PAGE_SIZE:
            return items
        page += 1


def find_pull_number(repository: str, owner: str) -> int | None:
    """The PR this run is about: an override, the event's, or the open PR of the pushed branch."""
    override = os.environ.get("PR_NUMBER")
    if override:
        return int(override)
    event_path = os.environ.get("GITHUB_EVENT_PATH")
    if event_path:
        event = cast(PullRequestEvent, json.loads(Path(event_path).read_text(encoding="utf-8")))
        if "pull_request" in event:
            return event["pull_request"]["number"]
    branch = os.environ.get("GITHUB_REF_NAME")
    if not branch:
        return None
    head = urllib.parse.quote(f"{owner}:{branch}", safe="")
    pulls = cast(list[PullRequest], fetch_json(f"/repos/{repository}/pulls?state=open&head={head}"))
    return pulls[0]["number"] if pulls else None


def is_by_owner(item: Review | ReviewComment, owner: str) -> bool:
    user = item["user"]
    return user is not None and user["login"] == owner and SESSION_FOOTER not in (item["body"] or "")


def collect_expected_entries(repository: str, owner: str, pull_number: int) -> list[ExpectedEntry]:
    reviews = cast(list[Review], fetch_all(f"/repos/{repository}/pulls/{pull_number}/reviews"))
    comments = cast(list[ReviewComment], fetch_all(f"/repos/{repository}/pulls/{pull_number}/comments"))
    review_entries = [
        ExpectedEntry(
            anchor=f"pullrequestreview-{review['id']}",
            label=f"review {review['id']}",
            url=review["html_url"],
        )
        for review in reviews
        if is_by_owner(review, owner) and review["state"] != PENDING_STATE and (review["body"] or "").strip()
    ]
    comment_entries = [
        ExpectedEntry(
            anchor=f"discussion_r{comment['id']}",
            label=f"comment on {comment['path']}:{comment['line'] or comment['original_line']}",
            url=comment["html_url"],
        )
        for comment in comments
        if is_by_owner(comment, owner)
    ]
    return review_entries + comment_entries


def find_open_headings(log: str) -> list[str]:
    """The heading of every round or comment whose outcome is still open."""
    return [
        HEADING_MARKS.sub("", entry.split("\n", maxsplit=1)[0])
        for entry in ENTRY_BOUNDARY.split(log)
        if OPEN_OUTCOME.search(entry)
    ]


def main() -> int:
    repository = os.environ.get("GITHUB_REPOSITORY")
    if not repository:
        raise RuntimeError("GITHUB_REPOSITORY is required")
    owner = repository.split("/", maxsplit=1)[0]

    pull_number = find_pull_number(repository, owner)
    if pull_number is None:
        print("No open pull request for this run; nothing to check.")
        return 0

    expected = collect_expected_entries(repository, owner, pull_number)
    if not expected:
        print(f"PR #{pull_number}: no submitted review from {owner} yet.")
        return 0

    log_path = Path(LOG_PATH_TEMPLATE.format(number=pull_number))
    log = log_path.read_text(encoding="utf-8") if log_path.exists() else ""

    open_headings = find_open_headings(log)
    for heading in open_headings:
        print(f"::warning file={log_path}::Open, waiting on a decision: {heading}")

    missing = [entry for entry in expected if entry.anchor not in log]
    if missing:
        for entry in missing:
            print(f"::error file={log_path}::No entry for {entry.label} ({entry.url})")
        print(
            f"{log_path}: {len(missing)} of {len(expected)} owner review items have no entry (reviews/AGENTS.md).",
            file=sys.stderr,
        )
        return 1

    print(f"{log_path}: all {len(expected)} owner review items logged; {len(open_headings)} still open.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
